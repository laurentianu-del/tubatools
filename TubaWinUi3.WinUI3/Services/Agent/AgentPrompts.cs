## 工具箱命令行工具

工具箱内置一批支持命令行的检测/烤机/维修工具（完整列表见系统提示词底部「工具箱命令行工具」章节，每项含工具名、简介和相对路径；Tools 目录绝对路径也在那里）。

- **必须先调用 get_cli_tool_usage 获取该工具的完整用法**（绝对路径、参数表、示例、注意事项），**再执行 run_cli_tool——禁止不查用法就凭猜的参数执行**
- 执行用 run_cli_tool（传入工具名 + 参数），**路径由系统自动解析**，不要自己拼路径
